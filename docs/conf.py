def _heat_transfer_tables():
    """Write the tables of the heat transfer coefficients of ExerPy from its data file."""
    here = os.path.dirname(os.path.abspath(__file__))
    with open(
        os.path.join(here, "..", "src", "exerpy", "data", "heat_transfer_coefficients.json"), encoding="utf-8"
    ) as f:
        data = json.load(f)
    cells = data["cells"]

    def spread(low, high):
        return f"{low:g}" if low == high else f"{low:g} to {high:g}"

    sources = {s for cell in cells for s in cell["sources"]}
    lines = [
        ".. Generated by docs/conf.py from src/exerpy/data/heat_transfer_coefficients.json.",
        "",
        f"The file holds {len(cells)} cells from {len(sources)} sources. "
        f"{sum(c['n_sources'] >= 3 for c in cells)} of them rest on three or more independent sources, "
        f"{sum(c['n_sources'] == 2 for c in cells)} on two and {sum(c['n_sources'] == 1 for c in cells)} on one. "
        "Where two cells share the exchanger type, the phases and the fluids, the one marked *default* is used.",
        "",
    ]
    for kind, name in data["exchanger_types"].items():
        rows = sorted(
            (c for c in cells if c["exchanger_type"] == kind),
            key=lambda c: (c["hot_fluid"], c["hot"], c["cold_fluid"], c["cold"], not c["default"]),
        )
        if not rows:
            continue
        lines += [
            f".. csv-table:: {name}, :math:`U` in W/(m² K)",
            '    :header: "Hot stream", "Cold stream", ":math:`U`", "Published range", '
            '"Values / sources", "Sources", "Construction and area basis", "Cell"',
            "    :widths: 14 14 7 11 9 16 21 8",
            "",
        ]
        for c in rows:
            cite = ":cite:`" + ",".join(c["sources"]) + "`"
            label = c["cell"] + (" default" if c["default"] and _shared(c, cells) else "")
            lines.append(
                f'    "{c["hot_fluid"]}, {c["hot"]}", "{c["cold_fluid"]}, {c["cold"]}", "{c["U"]:g}", '
                f'"{spread(*c["range"])}", "{c["n_values"]} / {c["n_sources"]}", "{cite}", '
                f'"{c["construction"]}; {c["area_basis"]}", "{label}"'
            )
        lines.append("")
    target = os.path.join(here, "_generated", "heat_transfer_coefficients.rst")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def _shared(cell, cells):
    """Whether another cell has the same exchanger type, phases and fluids."""
    key = ("exchanger_type", "hot", "cold", "hot_fluid", "cold_fluid")
    return sum(all(c[k] == cell[k] for k in key) for c in cells) > 1


_heat_transfer_tables()

